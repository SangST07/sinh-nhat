-- Chạy toàn bộ nội dung này một lần trong Supabase > SQL Editor > New query > Run.
create table if not exists public.birthday_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 28),
  message text not null check (char_length(trim(message)) between 1 and 180),
  created_at timestamptz not null default now()
);

alter table public.birthday_wishes enable row level security;

grant select, insert on public.birthday_wishes to anon, authenticated;
grant usage, select on sequence public.birthday_wishes_id_seq to anon, authenticated;

drop policy if exists "Anyone can read birthday wishes" on public.birthday_wishes;
create policy "Anyone can read birthday wishes"
  on public.birthday_wishes for select to anon, authenticated using (true);

drop policy if exists "Anyone can add birthday wishes" on public.birthday_wishes;
create policy "Anyone can add birthday wishes"
  on public.birthday_wishes for insert to anon, authenticated
  with check (
    char_length(trim(name)) between 1 and 28
    and char_length(trim(message)) between 1 and 180
  );

notify pgrst, 'reload schema';
